/// Local icon file for an item, if one is bundled.
pub fn local_item_image(name: &str) -> Option<&'static str> {
    ITEM_IMAGES.binary_search_by(|(n, _)| (*n).cmp(name)).ok().map(|i| ITEM_IMAGES[i].1)
}
